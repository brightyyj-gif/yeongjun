package a0727;

public class Switch1 {
    public static void main(String[] args) {
        int menu = 2;

        switch (menu) {
            case 1:
                System.out.println("김밥");
                break;
            
            case 2:
                System.out.println("라면");
                break;

            case 3:
                System.out.println("돈가스");
                break;

            default:
                break;
        }
    }
}
