package a0722;

public class Compare {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println("a == b " + (a == b)); // false
        System.out.println("a != b " + (a != b)); // true
        System.out.println("a > b " + (a > b)); // flase
        System.out.println("a < b " + (a < b)); // true
        System.out.println("a >= b " + (a >= b)); // false
        System.out.println("a <= b " + (a <= b)); // true
    }
}
